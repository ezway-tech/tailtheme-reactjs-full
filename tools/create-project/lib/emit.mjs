/** Emit a trimmed UI barrel from selected component basenames. Uses re-exports from Full index chunks. */
export function emitUiBarrel(sourceRoot, componentNames) {
  const fullIndex = fs.readFileSync(path.join(sourceRoot, 'src/components/ui/index.ts'), 'utf8');
  const blocks = fullIndex.split(/\n(?=export )/g);
  const selected = new Set(componentNames);
  const kept = [];
  for (const block of blocks) {
    const m = block.match(/from '\.\/([^']+)'/);
    if (!m) continue;
    if (selected.has(m[1])) kept.push(block.trimEnd());
  }
  return `${kept.join('\n\n')}\n`;
}

export function writeGenerated(destRoot, plan, { dryRun = false, skipRoutes = false } = {}) {
  const files = {};

  // Free-scope `lite` ships static routes/nav/urls via overrides — do not emit starter files.
  if (!skipRoutes) {
    files['src/routes/urls.ts'] = emitUrlsTs(plan.urls, plan.homePath);
    files['src/navigation/app-nav-tree.ts'] = emitNavTreeTs(plan.routeEntries);
    files['src/routes/route-objects.tsx'] = emitRouteObjectsTs(plan.routeEntries, plan.homePath);
  }

  if (!skipRoutes && plan.emitUiBarrel?.length) {
    files['src/components/ui/index.ts'] = emitUiBarrel(plan.sourceRoot, plan.emitUiBarrel);
  }

  const written = [];
  for (const [rel, content] of Object.entries(files)) {
    if (content == null) continue;
    written.push(rel);
    if (dryRun) continue;
    const abs = path.join(destRoot, rel);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, content, 'utf8');
  }
  return written;
}
